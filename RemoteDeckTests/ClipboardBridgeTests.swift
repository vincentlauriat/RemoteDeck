import AppKit
import Testing
import RFBKit
@testable import RemoteDeck

/// `ClipboardBridge` on an in-memory pasteboard (never the real one), no timer: `poll()` is called
/// by hand.
@MainActor
struct ClipboardBridgeTests {
    let pasteboard = InMemoryPasteboard()
    let sent = Sent()

    @MainActor final class Sent {
        var texts: [String] = []
        var tooLarge = 0
    }

    func bridge(enabled: Bool = true, running: Bool = true, key: Bool = true) -> ClipboardBridge {
        let bridge = ClipboardBridge(pasteboard: pasteboard, isEnabled: enabled, pollInterval: nil)
        bridge.send = { [sent] in sent.texts.append($0) }
        bridge.onTooLarge = { [sent] in sent.tooLarge += 1 }
        if running { bridge.sessionStarted() }
        bridge.windowKeyChanged(key)
        return bridge
    }

    @Test func sendsTheCurrentTextWhenKeyAndEachChangeOnce() {
        pasteboard.content = .text("first")
        let bridge = bridge()
        #expect(sent.texts == ["first"])
        bridge.poll()
        #expect(sent.texts == ["first"])   // unchanged count: not read again
        #expect(pasteboard.reads == 1)
        pasteboard.content = .text("second")
        bridge.poll()
        #expect(sent.texts == ["first", "second"])
    }

    @Test func aWindowThatIsNotKeyNeverReadsThePasteboard() {
        pasteboard.content = .text("for another app")
        let bridge = bridge(key: false)
        bridge.poll()
        #expect(pasteboard.reads == 0)
        #expect(sent.texts.isEmpty)
        bridge.windowKeyChanged(true)
        #expect(sent.texts == ["for another app"])
        bridge.windowKeyChanged(false)
        pasteboard.content = .text("later")
        bridge.poll()
        #expect(sent.texts == ["for another app"])
    }

    @Test func nothingIsSentBeforeTheSessionRuns() {
        pasteboard.content = .text("early")
        let bridge = bridge(running: false)
        bridge.poll()
        #expect(pasteboard.reads == 0)
        bridge.sessionStarted()
        #expect(sent.texts == ["early"])
        bridge.sessionStopped()
        bridge.receive("after stop")
        #expect(pasteboard.content == .text("early"))
    }

    /// Password managers mark secrets with org.nspasteboard.ConcealedType: never sent.
    @Test func concealedItemsAreNotSent() {
        pasteboard.content = .excluded
        let bridge = bridge()
        bridge.poll()
        #expect(sent.texts.isEmpty)
        pasteboard.content = .text("plain")
        bridge.poll()
        #expect(sent.texts == ["plain"])
    }

    /// 1Password, Bitwarden and the like add org.nspasteboard.ConcealedType next to the password.
    @Test func systemPasteboardNeverReadsAMarkedItem() {
        var reads = 0
        let read: () -> String? = { reads += 1; return "hunter2" }
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType"] {
            let types: [NSPasteboard.PasteboardType] = [.string, NSPasteboard.PasteboardType(marker)]
            #expect(SystemPasteboard.content(types: types, string: read) == .excluded)
        }
        #expect(reads == 0)
        #expect(SystemPasteboard.content(types: [.png], string: read) == .none)
        #expect(reads == 0)
        #expect(SystemPasteboard.content(types: [.string], string: read) == .text("hunter2"))
    }

    @Test func systemPasteboardExcludesTheNSPasteboardMarkers() {
        #expect(SystemPasteboard.excludedTypes.map(\.rawValue).sorted() == [
            "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        ])
    }

    @Test func remoteTextIsWrittenAndNotEchoedBack() {
        let bridge = bridge()
        bridge.receive("from remote")
        #expect(pasteboard.content == .text("from remote"))
        let reads = pasteboard.reads
        bridge.poll()   // the count changed by our own write: not even read back
        #expect(pasteboard.reads == reads)
        #expect(sent.texts.isEmpty)
        // A server echoing what was just sent does not rewrite the pasteboard.
        pasteboard.content = .text("local")
        bridge.poll()
        let count = pasteboard.changeCount
        bridge.receive("local")
        #expect(pasteboard.changeCount == count)
        #expect(sent.texts == ["local"])
    }

    /// Copy "A" here (sent), copy "C" in another app (window not key, no poll), then copy "A" on the
    /// remote: that is a new remote copy, not an echo, and must land on the pasteboard.
    @Test func remoteCopyOfTheLastSharedTextAfterALocalCopyElsewhereIsWritten() {
        pasteboard.content = .text("A")
        let bridge = bridge()
        #expect(sent.texts == ["A"])
        bridge.windowKeyChanged(false)
        pasteboard.content = .text("C")
        bridge.receive("A")
        #expect(pasteboard.content == .text("A"))
    }

    /// On the Latin-1 path "10 €\r\n" reaches the server as "10 ?\n": its echo must not replace the
    /// local original with the degraded text.
    @Test func serverEchoOfTheDegradedFormIsNotWritten() {
        pasteboard.content = .text("10 €\r\n")
        let bridge = bridge()
        bridge.shared("10 €\r\n", outcome: .sent(echo: "10 ?\n"))
        let count = pasteboard.changeCount
        bridge.receive("10 ?\n")
        #expect(pasteboard.content == .text("10 €\r\n"))
        #expect(pasteboard.changeCount == count)
    }

    @Test func remoteTextBeforeTheFirstFrameIsWrittenAtStart() {
        let bridge = bridge(running: false)
        bridge.receive("early remote")
        #expect(pasteboard.content == PasteboardContent.none)
        bridge.sessionStarted()
        #expect(pasteboard.content == .text("early remote"))
        #expect(sent.texts.isEmpty)   // not sent back
    }

    /// RFBKit refused it (over the server's limit, no notify): "Clipboard too large".
    @Test func refusedAsTooLargeByRFBKitIsReported() {
        pasteboard.content = .text("long")
        let bridge = bridge()
        bridge.shared("long", outcome: .tooLarge)
        #expect(sent.tooLarge == 1)
        bridge.shared("stale", outcome: .tooLarge)   // not the current text: ignored
        #expect(sent.tooLarge == 1)
    }

    @Test func remoteTextIsWrittenEvenWhenNotKey() {
        let bridge = bridge(key: false)
        bridge.receive("copied remotely")
        #expect(pasteboard.content == .text("copied remotely"))
    }

    @Test func tooLargeTextIsNotSentAndReportedOnce() {
        pasteboard.content = .text(String(repeating: "x", count: ServerMessageDecoder.maxCutTextLength + 1))
        let bridge = bridge()
        bridge.poll()
        #expect(sent.texts.isEmpty)
        #expect(sent.tooLarge == 1)
    }

    @Test func disabledExchangesNothingUntilTurnedOn() {
        pasteboard.content = .text("local")
        let bridge = bridge(enabled: false)
        bridge.receive("remote")
        bridge.poll()
        #expect(pasteboard.reads == 0)
        #expect(pasteboard.content == .text("local"))
        #expect(sent.texts.isEmpty)
        bridge.isEnabled = true
        #expect(sent.texts == ["local"])
    }
}
